-- BarangayLink database schema (PostgreSQL, used on Supabase)
-- Run this in the Supabase SQL Editor on a fresh database.
-- Timestamps are stored in Manila time. Row Level Security is switched on for
-- every table with no policies, because only the server connects to the database.

CREATE TABLE IF NOT EXISTS users (
  user_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email              VARCHAR(255) NOT NULL UNIQUE,
  password_hash      VARCHAR(255) NOT NULL,
  role               VARCHAR(20) NOT NULL DEFAULT 'resident'
                     CHECK (role IN ('resident', 'admin')),
  is_active          BOOLEAN NOT NULL DEFAULT TRUE,
  termination_reason VARCHAR(255),
  date_created       TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'Asia/Manila')
);

CREATE TABLE IF NOT EXISTS residents (
  resident_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id              INTEGER NOT NULL UNIQUE REFERENCES users(user_id),
  last_name            VARCHAR(100) NOT NULL,
  first_name           VARCHAR(100) NOT NULL,
  birthdate            DATE NOT NULL,
  address              VARCHAR(255) NOT NULL,
  contact_no           VARCHAR(20),
  id_file_path         VARCHAR(255),
  verification_status  VARCHAR(20) NOT NULL DEFAULT 'Unverified'
                       CHECK (verification_status IN ('Unverified', 'Pending', 'Verified', 'Rejected')),
  verification_remarks VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS document_types (
  document_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_name    VARCHAR(100) NOT NULL,
  description      VARCHAR(255),
  is_active        BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS document_requests (
  request_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resident_id      INTEGER NOT NULL REFERENCES residents(resident_id),
  document_type_id INTEGER NOT NULL REFERENCES document_types(document_type_id),
  purpose          VARCHAR(255) NOT NULL,
  status           VARCHAR(20) NOT NULL DEFAULT 'Pending'
                   CHECK (status IN ('Pending', 'Processing', 'Ready for Pickup',
                                     'Completed', 'Denied', 'Cancelled')),
  admin_notes      VARCHAR(255),
  processed_by     INTEGER REFERENCES users(user_id),
  requested_at     TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'Asia/Manila'),
  updated_at       TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'Asia/Manila')
);

CREATE TABLE IF NOT EXISTS facilities (
  facility_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  facility_name VARCHAR(100) NOT NULL,
  description   VARCHAR(255),
  capacity      INTEGER,
  is_active     BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS reservations (
  reservation_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resident_id         INTEGER NOT NULL REFERENCES residents(resident_id),
  facility_id         INTEGER NOT NULL REFERENCES facilities(facility_id),
  reservation_date    DATE NOT NULL,
  start_time          TIME NOT NULL,
  end_time            TIME NOT NULL,
  purpose             VARCHAR(255) NOT NULL,
  equipment_needs     VARCHAR(255),
  supporting_doc_path VARCHAR(255),
  status              VARCHAR(20) NOT NULL DEFAULT 'Pending'
                      CHECK (status IN ('Pending', 'Approved', 'Rejected', 'Cancelled')),
  admin_notes         VARCHAR(255),
  processed_by        INTEGER REFERENCES users(user_id),
  requested_at        TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'Asia/Manila'),
  updated_at          TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'Asia/Manila'),
  CHECK (end_time > start_time)
);

CREATE TABLE IF NOT EXISTS notifications (
  notification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         INTEGER NOT NULL REFERENCES users(user_id),
  message         VARCHAR(255) NOT NULL,
  link            VARCHAR(255),
  is_read         BOOLEAN NOT NULL DEFAULT FALSE,
  date_created    TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'Asia/Manila')
);

-- Announcements shown on the login page and the resident home page.
-- Only one announcement is pinned at a time (the app enforces this).
CREATE TABLE IF NOT EXISTS announcements (
  announcement_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title           VARCHAR(100) NOT NULL,
  message         VARCHAR(500) NOT NULL,
  is_pinned       BOOLEAN NOT NULL DEFAULT FALSE,
  is_active       BOOLEAN NOT NULL DEFAULT TRUE,
  date_posted     TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'Asia/Manila')
);

-- Upcoming barangay events shown next to the announcements.
CREATE TABLE IF NOT EXISTS events (
  event_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       VARCHAR(100) NOT NULL,
  description VARCHAR(255),
  event_date  DATE NOT NULL,
  start_time  TIME,
  venue       VARCHAR(100),
  audience    VARCHAR(50) NOT NULL DEFAULT 'Everyone',
  is_active   BOOLEAN NOT NULL DEFAULT TRUE
);

-- Row Level Security: on, with no policies. Only the server connects.
ALTER TABLE users             ENABLE ROW LEVEL SECURITY;
ALTER TABLE residents         ENABLE ROW LEVEL SECURITY;
ALTER TABLE document_types    ENABLE ROW LEVEL SECURITY;
ALTER TABLE document_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE facilities        ENABLE ROW LEVEL SECURITY;
ALTER TABLE reservations      ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications     ENABLE ROW LEVEL SECURITY;
ALTER TABLE announcements     ENABLE ROW LEVEL SECURITY;
ALTER TABLE events            ENABLE ROW LEVEL SECURITY;

